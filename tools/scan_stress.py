def narrator_lines():
    lines = SCRIPT.read_text(encoding="utf-8").splitlines()
    found = []
    for index, line in enumerate(lines):
        match = NARRATOR_RE.match(line.strip())
        if not match:
            continue
        for following in lines[index + 1:index + 5]:
            stripped = following.strip()
            if not stripped or stripped.startswith("#"):
                continue
            say = SAY_RE.match(stripped)
            if say:
                found.append((match.group(1), say.group(1), index + 1))
            break
    return found


def main():
    lines = narrator_lines()
    seen = {}
    dupes = 0
    hits = []
    out = []
    out.append("=== ALL NARRATOR LINES (%d) ===" % len(lines))
    for h, t, ln in lines:
        if h in seen:
            dupes += 1
        seen[h] = t
        out.append("%s  L%d  %s" % (h, ln, t))
        low = t.lower()
        for word, note in SUBSTR_TRAPS.items():
            if word in low:
                # контекст +- 40 символов вокруг
                pos = 0
                while True:
                    pos = low.find(word, pos)
                    if pos < 0:
                        break
                    ctx = t[max(0, pos - 30):pos + len(word) + 30]
                    hits.append("%s|%s|%s|%s" % (h, word, note, ctx))
                    pos += len(word)
    out.append("")
    out.append("=== TRAP HITS ===")
    out.extend(hits)
    REPORT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("lines", len(lines), "unique", len(seen), "dupes", dupes)
    print("hits", len(hits))
    # счётчик по словам-ловушкам, ASCII-only
    from collections import Counter
    c = Counter(h.split("|")[1] for h in hits)
    for word, n in sorted(c.items()):
        print(word, n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
